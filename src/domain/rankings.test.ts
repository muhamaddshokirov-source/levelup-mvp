import { URL } from 'node:url';
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const a = '00000000-0000-4000-8000-000000000001';
const b = '00000000-0000-4000-8000-000000000002';
const admin = '00000000-0000-4000-8000-000000000003';
const answer = 'I want to learn English because I enjoy meeting new people and sharing my ideas with friends from different countries every day.';
test('real PostgreSQL: shared XP, replay safety, private tables, roles and audited moderation', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      insert into auth.users values('${a}'),('${b}'),('${admin}');`);
    await db.exec(readFileSync(new URL('../../supabase/migrations/202610240001_rankings.sql', import.meta.url), 'utf8'));
    const as = async (id: string, role = 'authenticated') => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec(`set role ${role}`); };
    const rpc = async (sql: string, args: unknown[] = []) => (await db.query<{ value: any }>(`select ${sql} as value`, args)).rows[0]!.value;
    await as('', 'anon');
    await assert.rejects(rpc("public.rank_board('all')"), /permission denied/);
    await as(a);
    await assert.rejects(db.query('select * from public.rank_events'), /permission denied/);
    await assert.rejects(db.query(`insert into public.rank_admins values('${a}')`), /permission denied/);
    await assert.rejects(rpc('public.rank_award($1,$2,$3)', ['daily','',answer]), /JOIN_REQUIRED/);
    await rpc('public.rank_join($1)', ['Muhammad']);
    await assert.rejects(rpc('public.rank_award($1,$2,$3)', ['daily','','short']), /INVALID_ANSWER/);
    await assert.rejects(rpc('public.rank_award($1,$2,$3)', ['lesson','invented',answer]), /INVALID_ACTIVITY/);
    assert.equal((await rpc('public.rank_award($1,$2,$3)', ['daily','',answer])).awarded, 50);
    assert.equal((await rpc('public.rank_award($1,$2,$3)', ['daily','',answer])).awarded, 0);
    assert.equal((await rpc('public.rank_award($1,$2,$3)', ['lesson','a1-intro',answer])).awarded, 20);
    assert.equal((await rpc('public.rank_award($1,$2,$3)', ['lesson','a1-intro',answer])).awarded, 0);
    await as(b); await rpc('public.rank_join($1)', ['Muhlisa']);
    await rpc('public.rank_award($1,$2,$3)', ['daily','',answer]);
    let board = await rpc("public.rank_board('all')");
    assert.deepEqual(board.rows.map((r: any) => [r.display_name,r.xp,r.position]), [['Muhammad',70,1],['Muhlisa',50,2]]);
    assert.equal(board.me.user_id,b);
    await assert.rejects(rpc('public.rank_admin_list(0)'), /ADMIN_REQUIRED/);
    await assert.rejects(rpc('public.rank_admin_moderate($1,true,true,$2)', [a,'test']), /ADMIN_REQUIRED/);
    await db.exec('reset role'); await db.query('insert into public.rank_admins values($1)', [admin]);
    await as(admin);
    assert.equal((await rpc('public.rank_account()')).admin,true);
    await rpc('public.rank_admin_moderate($1,true,true,$2)', [a,'Duplicate account investigation']);
    assert.equal((await rpc('public.rank_admin_list(0)')).audit.length,1);
    assert.equal((await rpc("public.rank_board('week')")).rows.length,1);
    await assert.rejects(rpc('public.rank_admin_moderate($1,true,true,$2)', [admin,'test']), /ADMIN_PROTECTED/);
    await as(a);
    await assert.rejects(rpc('public.rank_award($1,$2,$3)', ['lesson','a1-day',answer]), /ACCOUNT_BLOCKED/);
    await rpc('public.rank_join($1)', ['New name']);
    assert.equal((await rpc('public.rank_account()')).banned,true, 'rejoin cannot unban');
    await as(b); await rpc('public.rank_leave()');
    assert.equal((await rpc("public.rank_board('all')")).rows.length,0);
    await rpc('public.rank_join($1)', ['Muhlisa']);
    assert.equal((await rpc("public.rank_board('all')")).me.xp,50, 'leave/rejoin keeps scores');
    await as(admin); await rpc('public.rank_admin_moderate($1,false,false,$2)', [a,'Investigation complete']);
    assert.equal((await rpc('public.rank_admin_list(0)')).audit.length,2);
    await db.exec('reset role');
    await db.exec(`update public.rank_events set created_at=now()-interval '30 days' where user_id='${a}'`);
    await as(b);
    assert.equal((await rpc("public.rank_board('week')")).rows[0].display_name,'Muhlisa');
    assert.equal((await rpc("public.rank_board('all')")).rows[0].display_name,'New name');
    await assert.rejects(rpc("public.rank_board('invalid')"), /INVALID_PERIOD/);
    await db.exec('reset role');
    for (let i = 0; i < 51; i++) {
      const id = (await db.query<{ id: string }>('insert into auth.users(id) values(gen_random_uuid()) returning id')).rows[0]!.id;
      await db.query('insert into public.rank_profiles(user_id,display_name) values($1,$2)',[id,`Fixture ${i}`]);
      await db.query("insert into public.rank_events(user_id,event_key,points) values($1,'fixture:1',50),($1,'fixture:2',50)",[id]);
    }
    await as(b);
    board = await rpc("public.rank_board('all')");
    assert.equal(board.rows.length,50);
    assert.equal(board.me.position,53,'own rank is available beyond top 50');
    assert.ok(!board.rows.some((r: any) => r.user_id===b));
    await assert.rejects(db.query('update public.rank_profiles set banned=false'), /permission denied/);
    await assert.rejects(db.query('delete from public.rank_events'), /permission denied/);
    await as('', 'authenticated'); await assert.rejects(rpc('public.rank_account()'), /AUTH_REQUIRED/);
  } finally { await db.close(); }
});
